package com.operators;

public class Bitwise_Operatoe 
{

	public static void main(String[] args) 
	{
       int a = 3;
       int b = 5;
       
       System.out.println(a&b); //and
       System.out.println(a|b); // OR
       System.out.println(a^b); // XOR/Exclusive OR
       System.out.println(a>>2); // right shift 2 number
       System.out.println(a<<3); //left shift 3 number
       System.out.println(~b); // ~not/Complement
       
	}

}
