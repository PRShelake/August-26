package com.operators;

public class Comparision_Operator 
{

	public static void main(String[] args) 
	{
      int x = 5;
      int y = 8;
      
     // boolean res = x>y; 
      
      System.out.println("x>y -> "+(x>y));
      System.out.println("x<y -> "+(x<y));
      System.out.println("x>=y -> "+(x>=y));
      System.out.println("x<=y -> "+(x<=y));
      System.out.println("x==y -> "+(x==y));
      System.out.println("x!=y -> "+(x!=y));
   //   System.out.println("x=<y"+(x=<y));
      

	}

}
