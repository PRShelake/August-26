package com.forloops;

public class Reverse_Number_Changing_Pyramid {

	public static void main(String[] args) {
		
		int i, j ;
		for( i = 6; i>=1; i--) {
			for (j=1; j<=i; j++) {
				System.out.print(j + " ");
//			    System.out.print(num++); 
		     }
            System.out.println( );
	}

	}
}


